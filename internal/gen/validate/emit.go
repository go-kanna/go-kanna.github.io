package validate

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/types"
	"strconv"
	"strings"

	"github.com/go-kanna/kanna/internal/imports"
)

// header marks the output as generated, in the words every kanna generator
// uses.
const header = "// Code generated by kanna. DO NOT EDIT.\n\n"

// formatRulesPath is the package holding the rules email, url, and uuid run.
const formatRulesPath = "github.com/go-kanna/validated/rules"

// maxDepth bounds the loop variables reserved against imports. A value nested
// deeper than this still gets its variables; only an import could then shadow
// one, which takes a package named like i12.
const maxDepth = 10

// The comparison that fails each requirement, and the error it reports.
var (
	failing = map[CmpOp]string{
		OpEQ: "!=", OpNE: "==", OpLT: ">=", OpLTE: ">", OpGT: "<=", OpGTE: "<",
	}
	compareErrors = map[CmpOp]string{
		OpEQ: "EqualTo", OpNE: "OtherThan",
		OpLT: "LessThan", OpLTE: "LessThanOrEqualTo",
		OpGT: "GreaterThan", OpGTE: "GreaterThanOrEqualTo",
	}
	lengthErrors = map[CmpOp]string{OpEQ: "WrongLength", OpLTE: "TooLong", OpGTE: "TooShort"}
)

// Emit renders the Validate methods of plans, which must all belong to one
// package named pkgName, as the source of one file. taken lists the names the
// package already declares at the top level, which the variables the file
// declares must not take.
func Emit(pkgName string, plans []Plan, taken []string) ([]byte, error) {
	if len(plans) == 0 {
		return nil, errors.New("emit: no plans")
	}
	pkgPath := plans[0].Struct.PkgPath
	for _, p := range plans[1:] {
		if p.Struct.PkgPath != pkgPath {
			return nil, fmt.Errorf("emit: plans span packages %s and %s", pkgPath, p.Struct.PkgPath)
		}
	}

	im := imports.New(pkgPath, nil)
	im.Reserve(taken...)
	im.Reserve("x", "errs")
	for depth := range maxDepth {
		im.Reserve(loopVar("i", depth), loopVar("k", depth), loopVar("v", depth))
	}

	e := &emitter{im: im, runtime: im.Add(runtimePath, "validate"), taken: make(map[string]bool)}
	for _, name := range taken {
		e.taken[name] = true
	}

	var body bytes.Buffer
	for _, p := range plans {
		e.method(&body, p)
	}

	var regexpPkg string
	if len(e.patterns) > 0 {
		regexpPkg = im.Add("regexp", "regexp")
	}

	var out bytes.Buffer
	out.WriteString(header)
	fmt.Fprintf(&out, "package %s\n\n", pkgName)
	imports.Render(&out, im.Entries(), importGroup)
	if len(e.patterns) > 0 {
		out.WriteString("\nvar (\n")
		for _, p := range e.patterns {
			fmt.Fprintf(&out, "%s = %s.MustCompile(%s)\n", p.name, regexpPkg, rawString(p.expr))
		}
		out.WriteString(")\n")
	}
	out.WriteString("\n")
	out.Write(body.Bytes())

	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("emit: gofmt: %w", err)
	}
	return src, nil
}

// emitter writes the methods of one file, recording what the file has to
// declare and import along the way.
type emitter struct {
	im *imports.Tracker

	// runtime is the name the file imports the validate runtime under.
	runtime string

	// patterns are the regular expressions the file compiles once, as package
	// variables.
	patterns []pattern

	// taken are the top-level names already in use in the package.
	taken map[string]bool
}

type pattern struct {
	name string
	expr string
}

// value is where a ValuePlan is rendered.
type value struct {
	// expr is the Go expression of the value, such as x.Name or (*x.Tags)[i].
	expr string

	// recv is the expression to call the value's methods on. For the value a
	// pointer points to, it is the pointer, which Go dereferences itself.
	recv string

	// path is the Go expression of the path errors report the value under.
	path string

	// nestPath is the path the value's own Validate nests its errors under,
	// which is empty for a flattened embedded struct.
	nestPath string

	// name names the package variables the value's patterns compile into.
	name string
}

func (e *emitter) method(b *bytes.Buffer, p Plan) {
	name := p.Struct.Name
	fmt.Fprintf(b, "// Validate checks x against the validate tags of %s. It returns the\n", name)
	fmt.Fprintf(b, "// %s.Errors of every rule x breaks, or nil.\n", e.runtime)
	fmt.Fprintf(b, "func (x %s) Validate() error {\n", name)
	fmt.Fprintf(b, "var errs %s.Errors\n", e.runtime)

	for _, f := range p.Fields {
		expr := "x." + f.Name
		path := strconv.Quote(f.Path)
		nestPath := path
		if f.Flatten {
			nestPath = `""`
		}
		b.WriteString("\n")
		e.value(b, f.Value, value{expr: expr, recv: expr, path: path, nestPath: nestPath, name: name + f.Name}, 0)
	}

	if p.Hook {
		b.WriteString("\nx.validate(&errs)\n")
	}
	b.WriteString("\nreturn errs.Err()\n}\n\n")
}

// value renders the checks of one value.
//
// A value that breaks required is reported blank and nothing else: whatever
// else an empty value breaks only says again that it is missing.
func (e *emitter) value(b *bytes.Buffer, v *ValuePlan, at value, depth int) {
	if v.Pointee != nil {
		e.pointer(b, v, at, depth)
		return
	}

	rest := len(v.Checks) > 0 || v.Nest || v.Elem != nil
	switch {
	case v.Required && !rest:
		fmt.Fprintf(b, "if %s {\nerrs.Add(%s, %s.Blank())\n}\n", e.zero(v, at), at.path, e.runtime)
		return
	case v.Required:
		fmt.Fprintf(b, "if %s {\nerrs.Add(%s, %s.Blank())\n} else {\n", e.zero(v, at), at.path, e.runtime)
	case v.OmitEmpty:
		fmt.Fprintf(b, "if %s {\n", e.nonZero(v, at))
	}

	for _, c := range v.Checks {
		e.check(b, c, v.Type, at)
	}

	if v.Nest {
		call := fmt.Sprintf("errs.Nest(%s, %s.Validate())\n", at.nestPath, at.recv)
		if types.IsInterface(v.Type) {
			call = fmt.Sprintf("if %s != nil {\n%s}\n", at.expr, call)
		}
		b.WriteString(call)
	}

	if v.Elem != nil {
		e.elem(b, v, at, depth)
	}

	if v.Required || v.OmitEmpty {
		b.WriteString("}\n")
	}
}

// pointer renders a pointer to a value with checks of its own: required
// tests the pointer for nil, and the rest checks what it points to, when there
// is something.
func (e *emitter) pointer(b *bytes.Buffer, v *ValuePlan, at value, depth int) {
	if v.Required {
		fmt.Fprintf(b, "if %s == nil {\nerrs.Add(%s, %s.Blank())\n} else {\n", at.expr, at.path, e.runtime)
	} else {
		fmt.Fprintf(b, "if %s != nil {\n", at.expr)
	}
	pointee := at
	pointee.expr = "*" + paren(at.expr)
	pointee.recv = paren(at.expr)
	e.value(b, v.Pointee, pointee, depth)
	b.WriteString("}\n")
}

// elem loops over the elements of a slice or array, or the values of a map,
// and renders v.Elem for each.
//
// A map whose keys have an order is walked in it, so that its errors come out
// in the same order on every run.
func (e *emitter) elem(b *bytes.Buffer, v *ValuePlan, at value, depth int) {
	elem := at
	if m, ok := v.Type.Underlying().(*types.Map); ok {
		k, val := loopVar("k", depth), loopVar("v", depth)
		if isOrdered(m.Key()) {
			fmt.Fprintf(b, "for _, %s := range %s.Sorted(%s.Keys(%s)) {\n%s := %s[%s]\n",
				k, e.im.Add("slices", "slices"), e.im.Add("maps", "maps"), at.expr, val, paren(at.expr), k)
		} else {
			fmt.Fprintf(b, "for %s, %s := range %s {\n", k, val, at.expr)
		}
		elem.expr, elem.recv = val, val
		elem.path = fmt.Sprintf("%s.Key(%s, %s)", e.runtime, at.path, k)
	} else {
		i := loopVar("i", depth)
		fmt.Fprintf(b, "for %s := range %s {\n", i, at.expr)
		elem.expr = paren(at.expr) + "[" + i + "]"
		elem.recv = elem.expr
		elem.path = fmt.Sprintf("%s.Index(%s, %s)", e.runtime, at.path, i)
	}
	elem.nestPath = elem.path
	e.value(b, v.Elem, elem, depth+1)
	b.WriteString("}\n")
}

func (e *emitter) check(b *bytes.Buffer, c Check, t types.Type, at value) {
	switch c := c.(type) {
	case LengthCheck:
		n := "len(" + at.expr + ")"
		if c.Runes {
			n = e.im.Add("unicode/utf8", "utf8") + ".RuneCountInString(" + asString(at.expr, t) + ")"
		}
		fmt.Fprintf(b, "if %s %s %d {\nerrs.Add(%s, %s.%s(%d))\n}\n",
			n, failing[c.Op], c.Bound, at.path, e.runtime, lengthErrors[c.Op], c.Bound)
	case CompareCheck:
		fmt.Fprintf(b, "if %s %s %s {\nerrs.Add(%s, %s.%s(%s))\n}\n",
			at.expr, failing[c.Op], c.Bound, at.path, e.runtime, compareErrors[c.Op], c.Bound)
	case OneOfCheck:
		conds := make([]string, len(c.Values))
		for i, v := range c.Values {
			conds[i] = at.expr + " != " + v
		}
		fmt.Fprintf(b, "if %s {\nerrs.Add(%s, %s.Inclusion())\n}\n", strings.Join(conds, " && "), at.path, e.runtime)
	case ConfirmCheck:
		fmt.Fprintf(b, "if %s != x.%s {\nerrs.Add(%s, %s.Confirmation(%s))\n}\n",
			at.expr, c.Field, at.path, e.runtime, strconv.Quote(c.Attribute))
	case PatternCheck:
		fmt.Fprintf(b, "if !%s.MatchString(%s) {\nerrs.Add(%s, %s.Invalid())\n}\n",
			e.pattern(at.name, c.Expr), asString(at.expr, t), at.path, e.runtime)
	case FormatCheck:
		fmt.Fprintf(b, "errs.Add(%s, %s.%s{}.Validate(%s))\n",
			at.path, e.im.Add(formatRulesPath, "rules"), c.Rule, asString(at.expr, t))
	}
}

// zero is the condition that holds for the zero value.
func (e *emitter) zero(v *ValuePlan, at value) string {
	switch v.Zero {
	case ZeroString:
		return at.expr + ` == ""`
	case ZeroNumber:
		return at.expr + " == 0"
	case ZeroBool:
		return "!" + at.expr
	case ZeroNil:
		return at.expr + " == nil"
	case ZeroMethod:
		return at.recv + ".IsZero()"
	case ZeroComposite:
		return at.expr + " == (" + types.TypeString(v.Type, e.im.Qualifier) + "{})"
	}
	panic(fmt.Sprintf("emit: unknown zero test %d", v.Zero))
}

// nonZero is the condition that holds for any value but the zero one.
func (e *emitter) nonZero(v *ValuePlan, at value) string {
	switch v.Zero {
	case ZeroString:
		return at.expr + ` != ""`
	case ZeroNumber:
		return at.expr + " != 0"
	case ZeroBool:
		return at.expr
	case ZeroNil:
		return at.expr + " != nil"
	case ZeroMethod:
		return "!" + at.recv + ".IsZero()"
	case ZeroComposite:
		return at.expr + " != (" + types.TypeString(v.Type, e.im.Qualifier) + "{})"
	}
	panic(fmt.Sprintf("emit: unknown zero test %d", v.Zero))
}

// pattern declares a package variable compiling expr, named after the value it
// checks, and returns its name.
func (e *emitter) pattern(name, expr string) string {
	base := "pattern" + name
	name = base
	for n := 2; e.taken[name]; n++ {
		name = base + strconv.Itoa(n)
	}
	e.taken[name] = true
	e.patterns = append(e.patterns, pattern{name: name, expr: expr})
	return name
}

// asString converts expr, of type t, to a string where a function needs one;
// a value of a type defined on string has to be converted.
func asString(expr string, t types.Type) string {
	if types.Identical(types.Unalias(t), types.Typ[types.String]) {
		return expr
	}
	return "string(" + expr + ")"
}

// isOrdered reports whether values of t can be sorted with <.
func isOrdered(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Info()&types.IsOrdered != 0
}

// paren wraps a dereference, so that indexing or calling a method applies to
// what it yields.
func paren(expr string) string {
	if strings.HasPrefix(expr, "*") {
		return "(" + expr + ")"
	}
	return expr
}

// loopVar names the loop variable of one depth: i, i1, i2, and so on.
func loopVar(base string, depth int) string {
	if depth == 0 {
		return base
	}
	return base + strconv.Itoa(depth)
}

// rawString quotes s as a raw string where it can, which keeps a regular
// expression as it was written in the tag.
func rawString(s string) string {
	if strconv.CanBackquote(s) {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// importGroup puts the standard library first, as goimports does.
func importGroup(e imports.Entry) int {
	if first, _, _ := strings.Cut(e.Path, "/"); strings.Contains(first, ".") {
		return 1
	}
	return 0
}

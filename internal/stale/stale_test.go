package stale_test

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/kanna/internal/packages"
	"github.com/go-kanna/kanna/internal/stale"
)

const header = "// Code generated by kanna. DO NOT EDIT.\n\n"

const model = `package app

type T struct{ A int }
`

// writeModule writes files into a fresh module and returns its directory.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	files["go.mod"] = "module example.com/app\n\ngo 1.27.0\n"
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// loadErrors returns every error the loaded packages carry.
func loadErrors(res *packages.Result) []string {
	var errs []string
	for _, pkg := range res.Packages {
		for _, e := range pkg.Errors {
			errs = append(errs, e.Error())
		}
	}
	return errs
}

func TestLoad(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		output      string
		content     string
		wantDropped bool
	}{
		{
			name:    "stale body",
			output:  "out_gen.go",
			content: header + "package app\n\nfunc (x T) B() int { return x.Missing }\n",
		},
		{
			// Dropping the body leaves strings unused and the comment with
			// nothing to attach to; both have to go for the stub to compile.
			name:   "stale body with its own import and comment",
			output: "out_gen.go",
			content: header + "package app\n\nimport \"strings\"\n\n" +
				"func (x T) B() string {\n\t// names what is gone\n\treturn strings.ToUpper(x.Missing)\n}\n",
		},
		{
			name:        "stale signature",
			output:      "out_gen.go",
			content:     header + "package app\n\nfunc NewT(g Gone) T { return T{} }\n",
			wantDropped: true,
		},
		{
			name:    "test output",
			output:  "out_gen_test.go",
			content: header + "package app\n\nfunc (x T) B() int { return x.Missing }\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"model.go": model, tt.output: tt.content})
			res, dropped, err := stale.Load([]string{"./..."}, packages.Config{Dir: dir, Tests: true},
				"out_gen.go", "out_gen_test.go")
			if err != nil {
				t.Fatalf("Load() error = %v", err)
			}
			if errs := loadErrors(res); len(errs) > 0 {
				t.Errorf("packages carry errors: %q", errs)
			}
			if got := len(dropped) > 0; got != tt.wantDropped {
				t.Errorf("dropped = %q, want dropped %v", dropped, tt.wantDropped)
			}
			for _, pkg := range res.Packages {
				if strings.HasSuffix(pkg.PkgPath, ".test") {
					t.Errorf("Load() kept the test binary %s", pkg.PkgPath)
				}
			}
		})
	}
}

// Only a generated file by one of the names the generator writes is set
// aside; anything else that breaks the package is reported as it is.
func TestLoad_LeavesOtherFiles(t *testing.T) {
	t.Parallel()

	stub := "package app\n\nfunc (x T) B() int { return x.Missing }\n"
	tests := []struct {
		name    string
		file    string
		content string
	}{
		{name: "another generator's output", file: "other_gen.go", content: header + stub},
		{name: "hand-written file", file: "out_gen.go", content: stub},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"model.go": model, tt.file: tt.content})
			res, dropped, err := stale.Load([]string{"./..."}, packages.Config{Dir: dir}, "out_gen.go")
			if err != nil {
				t.Fatalf("Load() error = %v", err)
			}
			errs := loadErrors(res)
			if !slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, "x.Missing undefined") }) {
				t.Errorf("errors = %q, want the one in %s", errs, tt.file)
			}
			if len(dropped) > 0 {
				t.Errorf("dropped = %q, want none", dropped)
			}
		})
	}
}

package validate_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/kanna/internal/diag"
	"github.com/go-kanna/kanna/internal/gen/validate"
	"github.com/go-kanna/kanna/internal/packages"
	"github.com/go-kanna/kanna/internal/pkgtest"
	"github.com/go-kanna/kanna/internal/scan"
)

// targets loads files as one package and returns its //kanna:validate structs
// by name, with every diagnostic rendered.
func targets(t *testing.T, files map[string]string) ([]string, []string) {
	t.Helper()

	pkg := pkgtest.LoadPackage(t, files)
	structs, ds := scan.Structs([]*packages.Package{pkg})
	if diag.HasErrors(ds) {
		t.Fatalf("scan: %s", diag.Format(ds))
	}

	got, diags := validate.Targets(pkg.Fset, structs)
	names := make([]string, len(got))
	for i, s := range got {
		names[i] = s.Name
	}
	msgs := make([]string, len(diags))
	for i, d := range diags {
		msgs[i] = d.String()
	}
	return names, msgs
}

func TestTargets(t *testing.T) {
	t.Parallel()

	names, msgs := targets(t, map[string]string{
		"model.go": `package test

//kanna:validate
type Marked struct {
	Name string ` + "`validate:\"required\"`" + `
}

//kanna:validate
type Regenerated struct{}

type Plain struct {
	Name string ` + "`json:\"name\"`" + `
}
`,
		// What an earlier run left behind, which the next run replaces.
		"validate_gen.go": `// Code generated by kanna-validate. DO NOT EDIT.

package test

func (x Regenerated) Validate() error { return nil }
`,
	})

	if want := []string{"Marked", "Regenerated"}; !slices.Equal(names, want) {
		t.Errorf("targets = %v, want %v", names, want)
	}
	if len(msgs) > 0 {
		t.Errorf("diagnostics = %q, want none", msgs)
	}
}

func TestTargets_Diagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "tags without the directive",
			src: `package test

type Forgotten struct {
	Name string ` + "`validate:\"required\"`" + `
}
`,
			want: "warning: Forgotten has validate tags but no //kanna:validate",
		},
		{
			name: "spaced directive",
			src: `package test

// kanna:validate
type Spaced struct{}
`,
			want: "is not recognized as a directive",
		},
		{
			name: "arguments",
			src: `package test

//kanna:validate strict
type WithArgs struct{}
`,
			want: `error: //kanna:validate takes no arguments, got "strict"`,
		},
		{
			name: "generic",
			src: `package test

//kanna:validate
type Box[T any] struct{ V T }
`,
			want: "error: generic struct Box is not supported",
		},
		{
			name: "field named Validate",
			src: `package test

//kanna:validate
type Clash struct{ Validate bool }
`,
			want: "error: Clash has a field named Validate",
		},
		{
			name: "hand-written Validate",
			src: `package test

//kanna:validate
type Manual struct{}

func (Manual) Validate() error { return nil }
`,
			want: "error: Manual already has a Validate method\n  declared at test.go:6:15",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			names, msgs := targets(t, map[string]string{"test.go": tt.src})
			if len(names) > 0 {
				t.Errorf("targets = %v, want none", names)
			}
			if !slices.ContainsFunc(msgs, func(m string) bool { return strings.Contains(m, tt.want) }) {
				t.Errorf("diagnostics = %q, want one containing %q", msgs, tt.want)
			}
		})
	}
}

#!/usr/bin/env python3
"""Assemble the site: the landing page, the assets, and a page per tool,
rendered from the README on its repository's default branch, each in English
and in Japanese.

    python3 pages/render.py [--out DIR]

The tool pages are not committed. The Pages workflow runs this on every push to
main and once a day, so the pages follow the READMEs, and the versions on the
landing page follow the tags and the go.mod files. To preview locally:

    python3 pages/render.py && python3 -m http.server -d _site

Needs the gh CLI, logged in: the READMEs are fetched and rendered through the
GitHub API, which keeps the pages looking as they do on GitHub.
"""
import argparse
import functools
import html
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = Path(__file__).resolve().parent / "page.html"
ORG = "go-kanna"
SITE = "https://go-kanna.github.io/"

# Each repository's page is at its name, headed with the tool's name.
TOOLS = [
    ("validate", "kanna-validate"),
    ("value", "kanna-value"),
    ("orm", "kanna-orm"),
    ("mapper", "kanna-mapper"),
    ("i18n", "kanna-i18n"),
    ("di", "kanna-di"),
    ("fixture", "kanna-fixture"),
]

# What differs between the languages of the site: where a language's pages sit,
# the README they come from, and what the template says around it.
LANGS = {
    "en": {
        "dir": "",
        "readme": "README.md",
        "root": "../",
        "home": "../",
        "locale": "en_US",
        "brand": "kanna home",
        "site_nav": "Site",
        "tools": "Tools",
        "on_this_page": "On this page",
        "licensed": "MIT licensed.",
        "coming_soon": "Coming soon",
        "source": 'This page is the <a href="https://github.com/go-kanna/{{repo}}#readme">README of go-kanna/{{repo}}</a>.',
        "switch": '<a href="../ja/{{repo}}/" hreflang="ja" lang="ja">日本語</a>',
    },
    "ja": {
        "dir": "ja/",
        "readme": "README.ja.md",
        "root": "../../",
        "home": "../",
        "locale": "ja_JP",
        "brand": "kanna ホーム",
        "site_nav": "サイト",
        "tools": "ツール",
        "on_this_page": "目次",
        "licensed": "MIT ライセンスです。",
        "coming_soon": "近日公開",
        "source": 'このページは <a href="https://github.com/go-kanna/{{repo}}/blob/main/README.ja.md">go-kanna/{{repo}} の README</a> です。',
        "switch": '<a href="../../{{repo}}/" hreflang="en" lang="en">English</a>',
    },
}

TAGS = re.compile(r"<[^>]+>")


def gh(*args, stdin=None):
    return subprocess.run(["gh", "api", *args], check=True, capture_output=True, text=True, input=stdin).stdout


def readme(repo, lang):
    return gh(f"repos/{ORG}/{repo}/contents/{LANGS[lang]['readme']}", "-H", "Accept: application/vnd.github.raw+json")


def render_markdown(text):
    # The markdown mode renders as GitHub renders a README; the gfm mode is for
    # comments, where every line break is one.
    return gh("markdown", "--input", "-", stdin=json.dumps({"text": text, "mode": "markdown"}))


@functools.cache
def latest_tag(repo):
    names = gh(f"repos/{ORG}/{repo}/tags", "--paginate", "--jq", ".[].name").split()
    versions = [n for n in names if re.fullmatch(r"v\d+\.\d+\.\d+", n)]
    return max(versions, key=lambda v: tuple(map(int, v[1:].split(".")))) if versions else None


@functools.cache
def go_version(repo):
    """The Go the module asks for, from the go directive of its go.mod."""
    gomod = gh(f"repos/{ORG}/{repo}/contents/go.mod", "-H", "Accept: application/vnd.github.raw+json")
    m = re.search(r"^go (\d+\.\d+)", gomod, flags=re.M)
    return f"Go {m.group(1)}" if m else None


def unwrap_headings(body):
    """Drop the permalink anchors GitHub puts beside headings, and the h1, which the page has its own of."""
    body = re.sub(r'<a id="user-content-[^"]*" class="anchor".*?</a>', "", body, flags=re.S)
    body = re.sub(r'<div class="markdown-heading">(<h[1-6].*?</h[1-6]>)</div>', r"\1", body, flags=re.S)
    return re.sub(r"\s*<h1[^>]*>.*?</h1>\s*", "", body, count=1, flags=re.S)


def scroll_tables(body):
    """Box each table, so that a wide one scrolls on a narrow screen instead of the page."""
    return re.sub(r"<table>.*?</table>", lambda m: f'<div class="table">{m.group(0)}</div>', body, flags=re.S)


def mark_generated(body):
    """Class the code blocks that show generated code, by the header it carries,
    so that they sit on the wood the site shows generated code on."""

    def mark(m):
        cls, code = m.groups()
        if "Code generated by" in html.unescape(TAGS.sub("", code)):
            cls += " generated"
        return f'<div class="{cls}"><pre>{code}</pre></div>'

    return re.sub(r'<div class="(highlight[^"]*)"><pre>(.*?)</pre></div>', mark, body, flags=re.S)


def absolutize(body, repo, lang):
    """Point the README's relative links at the repository, since the page is not
    in it, and its badge for the other language at that language's page."""
    pages = {conf["readme"]: f"{LANGS[lang]['root']}{conf['dir']}{repo}/" for conf in LANGS.values()}

    def absolute(m):
        attr, url = m.groups()
        if url in pages:
            return f'{attr}="{pages[url]}"'
        if re.match(r"[a-z][a-z0-9+.-]*:|#|//", url):
            return m.group(0)
        host = "https://raw.githubusercontent.com" if attr == "src" else "https://github.com"
        path = "main" if attr == "src" else "blob/main"
        return f'{attr}="{host}/{ORG}/{repo}/{path}/{url.removeprefix("./")}"'

    return re.sub(r'\b(href|src)="([^"]*)"', absolute, body)


def slugify(heading):
    """The id GitHub gives a heading, so that the README's own links keep working."""
    text = html.unescape(TAGS.sub("", heading)).strip().lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


def anchor_headings(body):
    seen = {}
    toc = []

    def anchor(m):
        level, attrs, inner = m.groups()
        slug = slugify(inner)
        n = seen.get(slug, 0)
        seen[slug] = n + 1
        if n:
            slug = f"{slug}-{n}"
        if level in ("2", "3"):
            toc.append((int(level), slug, inner))
        return f'<h{level} id="{slug}"{attrs}>{inner}</h{level}>'

    return re.sub(r"<h([1-6])([^>]*)>(.*?)</h\1>", anchor, body, flags=re.S), toc


def render_toc(toc):
    sections = []
    for level, slug, inner in toc:
        if level == 2 or not sections:
            sections.append((slug, inner, []))
        else:
            sections[-1][2].append((slug, inner))

    def item(slug, inner, children=()):
        sub = f"<ol>{''.join(item(*c) for c in children)}</ol>" if children else ""
        return f'<li><a href="#{slug}">{inner}</a>{sub}</li>'

    return f"<ol>{''.join(item(*s) for s in sections)}</ol>"


def description(body):
    """The first paragraph that is text, after the badges."""
    for m in re.finditer(r"<p[^>]*>(.*?)</p>", body, flags=re.S):
        text = " ".join(html.unescape(TAGS.sub("", m.group(1))).split())
        if text:
            return text
    return ""


def alternates(repo):
    """The links telling a search engine which page is which language's."""
    links = [(lang, f"{SITE}{conf['dir']}{repo}/") for lang, conf in LANGS.items()]
    links.append(("x-default", f"{SITE}{repo}/"))
    return "\n".join(f'<link rel="alternate" hreflang="{lang}" href="{url}">' for lang, url in links)


def render_page(template, repo, name, lang):
    body = mark_generated(scroll_tables(unwrap_headings(render_markdown(readme(repo, lang)))))
    body = absolutize(body, repo, lang)
    body, toc = anchor_headings(body)
    page = template
    for key, value in {
        "lang": lang,
        **LANGS[lang],
        "name": name,
        "repo": repo,
        "alternates": alternates(repo),
        "description": html.escape(description(body), quote=True),
        "version": latest_tag(repo) or LANGS[lang]["coming_soon"],
        "go": go_version(repo) or "",
        "toc": render_toc(toc),
        "body": body,
    }.items():
        page = page.replace("{{" + key + "}}", value)
    return page


def stamp(page):
    """Fill in what the landing page says of each repository: the latest tag
    where an element carries data-tag, and the Go its go.mod asks for where one
    carries data-go. What the page says already stands when the lookup finds
    nothing."""

    def fill(lookup, m):
        start, repo, text, end = m.groups()
        return f"{start}{lookup(repo.split('/')[1]) or text}{end}"

    page = re.sub(r'(<a[^>]*\bdata-tag="([^"]+)"[^>]*>)([^<]*)(</a>)', lambda m: fill(latest_tag, m), page)
    return re.sub(r'(<span[^>]*\bdata-go="([^"]+)"[^>]*>)([^<]*)(</span>)', lambda m: fill(go_version, m), page)


def main():
    parser = argparse.ArgumentParser(description="Assemble the site into a directory.")
    parser.add_argument("--out", type=Path, default=ROOT / "_site", help="directory to write (default: _site)")
    parser.add_argument("--base", default="/",
                        help="path the site is served under, which the 404 page needs to find the rest (default: /)")
    args = parser.parse_args()
    out = args.out

    out.mkdir(parents=True, exist_ok=True)
    (out / "ja").mkdir(exist_ok=True)
    for landing in ("index.html", "ja/index.html"):
        (out / landing).write_text(stamp((ROOT / landing).read_text()))
    # Served for any path under the site, so it finds the rest from the root.
    (out / "404.html").write_text(TEMPLATE.with_name("404.html").read_text().replace("{{base}}", args.base))
    shutil.copytree(
        ROOT / "assets", out / "assets", dirs_exist_ok=True, ignore=shutil.ignore_patterns("*.py", "*.md", ".DS_Store")
    )
    template = TEMPLATE.read_text()
    for repo, name in TOOLS:
        for lang, conf in LANGS.items():
            page = out / conf["dir"] / repo / "index.html"
            page.parent.mkdir(exist_ok=True)
            page.write_text(render_page(template, repo, name, lang))
            print(page.relative_to(out))


if __name__ == "__main__":
    main()
